-- 1. TABLA: categories
CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT,
    storage_temp_c NUMERIC DEFAULT 18.0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. TABLA: suppliers
CREATE TABLE IF NOT EXISTS suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name TEXT NOT NULL,
    contact_name TEXT NOT NULL,
    phone TEXT NOT NULL,
    origin_region TEXT NOT NULL,
    quality_grade TEXT DEFAULT 'Cacao Fino de Aroma - Primera',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. TABLA: products
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    price NUMERIC NOT NULL,
    stock INTEGER DEFAULT 0 NOT NULL,
    cocoa_percentage INTEGER DEFAULT 70 NOT NULL,
    weight_grams INTEGER DEFAULT 100 NOT NULL,
    image_url TEXT,
    category_id BIGINT REFERENCES categories(id) ON DELETE CASCADE NOT NULL,
    supplier_id BIGINT REFERENCES suppliers(id) ON DELETE RESTRICT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. TABLA: clients
CREATE TABLE IF NOT EXISTS clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_name TEXT NOT NULL,
    contact_owner TEXT NOT NULL,
    nit_ci TEXT UNIQUE NOT NULL,
    phone TEXT NOT NULL,
    zone_address TEXT NOT NULL,
    business_type TEXT DEFAULT 'Mayorista' NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. TABLA: orders
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT REFERENCES clients(id) ON DELETE CASCADE NOT NULL,
    product_id BIGINT REFERENCES products(id) ON DELETE CASCADE NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC NOT NULL,
    total_price NUMERIC NOT NULL,
    status TEXT DEFAULT 'Completado' NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ====================================================================
-- POLÍTICAS DE SEGURIDAD (Row Level Security - RLS)
-- Permite lectura y escritura pública para el prototipo
-- ====================================================================
ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE suppliers ENABLE ROW LEVEL SECURITY;
ALTER TABLE products ENABLE ROW LEVEL SECURITY;
ALTER TABLE clients ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Permitir select publico categories" ON categories FOR ALL USING (true);
CREATE POLICY "Permitir select publico suppliers" ON suppliers FOR ALL USING (true);
CREATE POLICY "Permitir select publico products" ON products FOR ALL USING (true);
CREATE POLICY "Permitir select publico clients" ON clients FOR ALL USING (true);
CREATE POLICY "Permitir select publico orders" ON orders FOR ALL USING (true);
